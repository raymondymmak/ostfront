import { readFileSync } from "node:fs"
import { describe, expect, it } from "vitest"

describe("top bar and map chrome", () => {
  const hud = readFileSync("components/hud.tsx", "utf8")
  const legend = readFileSync("components/map-legend.tsx", "utf8")
  const map = readFileSync("components/war-map.tsx", "utf8")
  const app = readFileSync("components/game-app.tsx", "utf8")
  const campaignStart = readFileSync("components/campaign-start.tsx", "utf8")

  it("keeps the labelled situation in the top bar and drops the scenario subtitle", () => {
    expect(hud).toContain("Ostfront")
    expect(hud).not.toContain("spec.name")
    expect(hud).not.toContain("spec.kicker")
    expect(hud).not.toContain("onOverlay")
    expect(hud).not.toContain("Control")
    expect(hud).toContain("Strength")
    expect(hud).not.toContain("Provinces")
    expect(hud).toContain("EconomyReadout")
    const readout = readFileSync("components/economy-readout.tsx", "utf8")
    expect(readout).toContain("Manpower")
    expect(readout).toContain("Industry")
    expect(readout).toContain('data-testid="treasury"')
    expect(readout).toContain('data-testid="economy-breakdown"')
    expect(readout).toContain("INCOME_FORMULA")
    expect(readout).toContain("REFIT_FORMULA")
    expect(hud).toContain("VP")
    expect(hud).toContain("Grade")
    expect(hud).toContain('data-testid="grade"')
    expect(hud).toContain('data-testid="objectives"')
    expect(hud).toContain("statusLabel")
    expect(hud).toContain("teachMode")
    expect(hud).toContain("tableShell")
    // Window toggles (incl. Chief of Staff) live in the document tray, not the HUD.
    expect(hud).not.toMatch(/data-testid="advisor-toggle"/)
    expect(hud).not.toContain("Chief of Staff")
    expect(hud).not.toContain("onAdvisor")
    expect(hud).toContain("HudOptionsMenu")
    expect(hud).toContain('data-testid="table-hud"')
    const panel = readFileSync("components/province-panel.tsx", "utf8")
    const kindAt = panel.indexOf("{KIND_LABEL[unit.kind]}")
    const nameAt = panel.indexOf("{unit.name}")
    expect(kindAt).toBeGreaterThan(-1)
    expect(nameAt).toBeGreaterThan(kindAt)
    expect(panel).toContain("morale {unit.morale}")
    expect(panel.slice(nameAt - 80, nameAt)).toContain("text-xs text-muted-foreground")
    const hover = readFileSync("lib/ui/map-hover.ts", "utf8")
    expect(hover).toContain("hoverBeyondBase")
    const warMap = readFileSync("components/war-map.tsx", "utf8")
    expect(warMap).toContain('data-testid="map-hover-tip"')
    expect(warMap).toContain("hoverBeyondBase")
    expect(warMap).not.toContain("absolute left-2 z-20 max-w-[min(14rem")
    expect(hud).not.toMatch(/>Restart</)
  })

  it("puts map mode on the map and the rails toggle inside the open legend", () => {
    expect(map).toContain("<MapMode")
    expect(map).toContain("onOverlay={onOverlay}")
    expect(app).toContain("onOverlay={setOverlay}")
    const hudCall = app.slice(app.indexOf("<Hud"), app.indexOf("/>", app.indexOf("<Hud")))
    expect(hudCall).not.toContain("overlay=")
    const openAt = legend.indexOf("{open &&")
    const toggleAt = legend.indexOf('data-testid="rail-toggle"')
    expect(toggleAt).toBeGreaterThan(openAt)
    expect(legend.slice(0, openAt)).not.toContain("rail-toggle")
    expect(legend).toContain('data-testid="overlay-scale"')
  })

  it("uses a desktop floating-window shell and keeps Log above the legend below lg", () => {
    expect(app).toContain("createDefaultTableWindows")
    expect(app).toContain("FloatingWindow")
    expect(app).toContain("OhlOrdersWindow")
    expect(app).toContain("tableShell={desktopShell}")
    expect(app).toContain("DocumentTray")
    expect(app).toContain("CAMPAIGN_TRAY_ITEMS")
    expect(app).toContain("CAMPAIGN_PHONE_TRAY_ITEMS")
    expect(app).toContain('sideTab === "advisor"')
    expect(app).toContain('sideTab === "ohl"')
    expect(app).toContain("OhlOrdersBody")
    expect(app).not.toContain("{!desktopShell && ohlOpen &&")
    expect(app).toContain("h-dvh max-h-dvh")
    expect(app).toContain("safe-area-inset-top")
    expect(app).not.toContain("min-h-[28rem]")
    const css = readFileSync("app/globals.css", "utf8")
    expect(css).toContain("height: 100dvh")
    expect(css).toContain("overscroll-behavior: none")
    expect(css).toContain("touch-action: none")
    const layout = readFileSync("app/layout.tsx", "utf8")
    expect(layout).toContain("overflow-hidden")
    expect(layout).toContain("overscroll-none")
    const trayLib = readFileSync("lib/ui/document-tray.ts", "utf8")
    expect(trayLib).toContain("CAMPAIGN_PHONE_TRAY_ITEMS")
    expect(trayLib).toContain("advisor-toggle")
    expect(hud).not.toContain("onToggleWindow")
    expect(hud).not.toContain("WindowToggle")
    const drawer = readFileSync("components/chronicle-drawer.tsx", "utf8")
    expect(drawer).toContain("bottom-14 left-3")
    expect(drawer).not.toMatch(/className="[^"]*sm:bottom-3/)
    expect(drawer).toContain("lg:hidden")
  })

  it("starts campaign and /teach with no province auto-selected", () => {
    expect(app).toMatch(/useState<string \| null>\(null\)/)
    expect(app).not.toMatch(/useState<string \| null>\("krakow"\)/)
    expect(app).toContain("setSelectedId(null)")
    expect(app).not.toContain('setSelectedId("krakow")')
    const teach = readFileSync("components/teaching-app.tsx", "utf8")
    expect(teach).toMatch(/useState<string \| null>\(null\)/)
    expect(teach).not.toMatch(/useState<string \| null>\("lublin"\)/)
    expect(teach).toContain("setSelectedId(null)")
    expect(teach).not.toContain("setSelectedId(payload.meta.targetProvinceId)")
    // demo-check still selects Kraków explicitly when a step needs it
    const demo = readFileSync("scripts/demo-check.mjs", "utf8")
    expect(demo).toContain("selectKrakowOnMap")
    expect(demo).toContain("krakowIsSelected")
    expect(demo).toContain("Expected no province selected at campaign start")
    // MapLibre selected filter sentinel must not count as a selection.
    expect(demo).toContain('id === "__none__"')
  })

  it("keeps the HUD above floating papers so Options restart stays clickable", () => {
    const css = readFileSync("app/globals.css", "utf8")
    expect(css).toContain(".table-hud")
    expect(css).toMatch(/z-index:\s*210/)
    const windows = readFileSync("lib/ui/table-windows.ts", "utf8")
    expect(windows).toContain("HUD_Z = PAPER_DRAG_Z + 10")
  })

  it("puts /teach on the same general's-table shell with lesson focus highlights", () => {
    const teach = readFileSync("components/teaching-app.tsx", "utf8")
    const hud = readFileSync("components/hud.tsx", "utf8")
    const map = readFileSync("components/war-map.tsx", "utf8")
    const panel = readFileSync("components/order-panel.tsx", "utf8")
    expect(teach).toContain("createDefaultTeachWindows")
    expect(teach).toContain("FloatingWindow")
    expect(teach).toContain("DocumentTray")
    expect(teach).toContain("TEACH_TRAY_ITEMS")
    expect(teach).toContain("bodyScroll={false}")
    expect(teach).toContain("lessonFocus=")
    expect(teach).toContain("tableShell={desktopShell}")
    expect(teach).toContain("hideEndTurn")
    expect(teach).toContain("teachGoal={session.meta.title}")
    expect(teach).toContain('data-testid="teach-lesson-stack"')
    expect(teach).toContain("h-dvh")
    expect(teach).toContain("overflow-hidden")
    expect(teach).not.toContain('endTurnLabel="Resolve this fortnight"')
    const panelSrc = readFileSync("components/teach-panel.tsx", "utf8")
    expect(panelSrc).toContain('data-testid="teach-resolve-bar"')
    expect(panelSrc).toContain('data-testid="teach-resolve"')
    expect(hud).not.toContain("onToggleTeachWindow")
    expect(hud).not.toContain("teach-lesson-toggle")
    expect(hud).toContain('data-testid="teach-goal"')
    expect(hud).not.toMatch(/teachMode &&[\s\S]*campaignGoalLine/)
    expect(panel).toContain("hideEndTurn")
    expect(map).toContain("data-lesson-highlights")
    expect(map).toContain("LESSON_TARGET_OUTLINE_LAYER")
    expect(map).toContain("applyLessonFocusLayers")
    expect(map).toContain("mapReady")
    const tray = readFileSync("components/document-tray.tsx", "utf8")
    expect(tray).toContain('data-testid="document-tray"')
    expect(tray).toContain("dropHighlight")
    expect(tray).not.toContain("onStow")
    const trayLib = readFileSync("lib/ui/document-tray.ts", "utf8")
    expect(trayLib).toContain("teach-lesson-toggle")
    const paper = readFileSync("components/floating-window.tsx", "utf8")
    expect(paper).not.toContain("floating-window-stow")
  })

  it("keeps start-card controls full-width inside the parchment card (no left-flush max-w)", () => {
    expect(campaignStart).toContain('data-testid="campaign-start-card"')
    expect(campaignStart).toContain('data-testid="campaign-start-actions"')
    expect(campaignStart).toContain('data-testid="difficulty"')
    expect(campaignStart).toMatch(/safe-area-inset-top/)
    expect(campaignStart).toMatch(/safe-area-inset-bottom/)
    const difficultyOpen = campaignStart.lastIndexOf("<div", campaignStart.indexOf('data-testid="difficulty"'))
    const difficultyBlock = campaignStart.slice(difficultyOpen, campaignStart.indexOf(">", campaignStart.indexOf('data-testid="difficulty"')) + 1)
    const actionsOpen = campaignStart.lastIndexOf("<div", campaignStart.indexOf('data-testid="campaign-start-actions"'))
    const actionsBlock = campaignStart.slice(
      actionsOpen,
      campaignStart.indexOf(">", campaignStart.indexOf('data-testid="campaign-start-actions"')) + 1,
    )
    expect(difficultyBlock).toMatch(/className="[^"]*\bw-full\b/)
    expect(actionsBlock).toMatch(/className="[^"]*\bw-full\b/)
    expect(difficultyBlock).not.toMatch(/max-w-/)
    expect(actionsBlock).not.toMatch(/max-w-/)
  })
})